"""Single entry point that produces every result Task 6.3/6.4's Definition of Done requires.

Runs the full Tokenizer x Dataset matrix (`experiments.runner`), exports it
as CSV and JSON to `data/results/` (`benchmarking.export`, Task 5.4), computes
the Task 6.4 aggregations, and (re)writes `docs/experiment_results.md` from
those real, just-computed results — never from invented numbers.

Usage (from the project root):

    python scripts/run_experiments.py

Reproducibility: re-running this script regenerates the same rows (see
`experiments.runner`'s docstring) with a fresh `timestamp`; commit the
regenerated `docs/experiment_results.md` if the underlying datasets,
tokenizers, or aggregation logic changed since it was last generated.
"""

from __future__ import annotations

import sys
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT / "src"))

import pandas as pd  # noqa: E402

from experiments.aggregation import (  # noqa: E402
    aggregate_by_group,
    aggregate_by_group_and_tokenizer,
    describe_observations,
)
from experiments.runner import ExperimentConfig, run_and_export_experiment  # noqa: E402

_RESULTS_DIR = _PROJECT_ROOT / "data" / "results"
_DOCS_PATH = _PROJECT_ROOT / "docs" / "experiment_results.md"


def _dataframe_to_markdown_table(df: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub-flavored Markdown table without extra dependencies."""
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    separator = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = [
        "| "
        + " | ".join(f"{v:.3g}" if isinstance(v, float) else str(v) for v in row)
        + " |"
        for row in df.itertuples(index=False)
    ]
    return "\n".join([header, separator, *rows])


def _highlight_extremes(by_language_and_tokenizer: pd.DataFrame) -> list[str]:
    """For each tokenizer, name the highest- and lowest-`tokens_per_word` category.

    A handful of targeted highlights are more useful to read than one
    sentence per every (language_or_type, tokenizer) pair — this is the
    "identify the most relevant observations" half of Task 6.4, kept
    separate from `describe_observations` (Task 6.4's complete, reusable,
    correctly-scoped sentence set), which the "Observations" section below
    still includes in full.
    """
    lines = []
    for tokenizer, group in by_language_and_tokenizer.groupby("tokenizer"):
        highest = group.loc[group["tokens_per_word_mean"].idxmax()]
        lowest = group.loc[group["tokens_per_word_mean"].idxmin()]
        lines.append(
            f"For tokenizer {tokenizer!r} in this experiment's dataset, "
            f"{highest['language_or_type']!r} needed the most tokens per word "
            f"({highest['tokens_per_word_mean']:.3g}) and {lowest['language_or_type']!r} "
            f"needed the fewest ({lowest['tokens_per_word_mean']:.3g})."
        )
    return lines


def _build_report(results: pd.DataFrame) -> str:
    by_language_and_tokenizer = aggregate_by_group_and_tokenizer(
        results, metrics=["tokens_per_word", "characters_per_token", "compression_ratio"]
    ).sort_values(["language_or_type", "tokenizer"])
    by_language = aggregate_by_group(
        results, metrics=["tokens_per_word", "compression_ratio"]
    ).sort_values("language_or_type")
    highlights = _highlight_extremes(by_language_and_tokenizer)
    observations = describe_observations(results, metric="tokens_per_word")

    lines = [
        "# Experiment results",
        "",
        "> **Generated by `scripts/run_experiments.py` from this project's own",
        "> tokenizers (Task 2-3) run on the datasets in `data/raw/` (Task 6.1),",
        "> through the Comparator (Task 5.3). These are real, just-computed",
        "> numbers, not illustrative examples — re-run the script to refresh them",
        "> after changing a tokenizer, a dataset, or the aggregation logic.**",
        "",
        "> **Scope note (Task 6.4.5):** every observation below describes what",
        "> happened *in this experiment's dataset* — a handful of KB of text per",
        "> category. None of it generalizes to a claim about an entire language",
        "> or text type; a single small corpus cannot support that.",
        "",
        "## Raw results",
        "",
        f"{len(results)} rows: {results['tokenizer'].nunique()} tokenizers x "
        f"{results['dataset'].nunique()} datasets.",
        "",
        "## Aggregated by language/type and tokenizer",
        "",
        _dataframe_to_markdown_table(by_language_and_tokenizer),
        "",
        "## Aggregated by language/type (across all tokenizers)",
        "",
        _dataframe_to_markdown_table(by_language),
        "",
        "## Highlights",
        "",
        *[f"- {sentence}" for sentence in highlights],
        "",
        "## All observations (per language/type and tokenizer)",
        "",
        *[f"- {sentence}" for sentence in observations],
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    results = run_and_export_experiment(
        ExperimentConfig(),
        csv_path=_RESULTS_DIR / "experiment_results.csv",
        json_path=_RESULTS_DIR / "experiment_results.json",
    )
    _DOCS_PATH.write_text(_build_report(results), encoding="utf-8")
    print(f"Wrote {len(results)} rows to {_RESULTS_DIR} and {_DOCS_PATH}")


if __name__ == "__main__":
    main()
